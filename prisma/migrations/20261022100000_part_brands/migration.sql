CREATE FUNCTION protect_brand_directory() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
 IF OLD.id = 'brand_unknown' AND (TG_OP = 'DELETE' OR NEW.id <> OLD.id OR NEW.name <> '---' OR NOT NEW."isActive") THEN
  RAISE EXCEPTION 'The unknown brand is a protected system record';
 END IF;
 IF TG_OP = 'DELETE' THEN RETURN OLD; END IF;
 NEW."updatedAt" = CURRENT_TIMESTAMP;
 RETURN NEW;
END;
$$;
